// Step 2 of the AMDM import: raw JSON (step 1) → CSV for Supabase Table Editor
// and SQL upsert files for SQL Editor. Run through scripts/amdm/build.sh.
//
// Usage: node scripts/amdm/build-csv.ts <raw.json> <out-dir>
// Output: <out-dir>/amdm_registry.csv, <out-dir>/amdm_sql/amdm_registry_NN.sql

import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { REGISTRY_COLUMNS, cleanRegistryRow, csvLine, upsertStatement, type RegistryRow } from "./clean.ts";

const SQL_BATCH = 500;
const ROWS_PER_FILE = 1000;

const [rawPath, outDir] = process.argv.slice(2);
if (!rawPath || !outDir) {
  console.error("Usage: node scripts/amdm/build-csv.ts <raw.json> <out-dir>");
  process.exit(2);
}

const raw = JSON.parse(readFileSync(rawPath, "utf8")) as { rows: unknown[][] };
const rows: RegistryRow[] = [];
const errors: string[] = [];
for (const r of raw.rows) {
  const res = cleanRegistryRow(r);
  if (res.ok) rows.push(res.row);
  else errors.push(res.error);
}

const codes = new Set(rows.map((r) => r.code));
if (errors.length > 0 || codes.size !== rows.length) {
  console.error(`Rejected rows: ${errors.length}; duplicate codes: ${rows.length - codes.size}`);
  errors.slice(0, 20).forEach((e) => console.error(`  ${e}`));
  process.exit(1);
}

// CSV (UTF-8, no BOM, LF; header = table column names).
const csv = [REGISTRY_COLUMNS.join(","), ...rows.map(csvLine)].join("\n") + "\n";
writeFileSync(join(outDir, "amdm_registry.csv"), csv, "utf8");

// SQL upsert files: each one fits SQL Editor and is safe to re-run.
const sqlDir = join(outDir, "amdm_sql");
mkdirSync(sqlDir, { recursive: true });
for (const f of readdirSync(sqlDir)) if (f.endsWith(".sql")) rmSync(join(sqlDir, f));
const files = Math.ceil(rows.length / ROWS_PER_FILE);
for (let f = 0; f < files; f++) {
  const chunk = rows.slice(f * ROWS_PER_FILE, (f + 1) * ROWS_PER_FILE);
  const parts = [`-- AMDM registry upsert, part ${f + 1} of ${files} (${chunk.length} rows). Generated by scripts/amdm.\nbegin;\n`];
  for (let i = 0; i < chunk.length; i += SQL_BATCH) parts.push(upsertStatement(chunk.slice(i, i + SQL_BATCH)));
  parts.push("commit;\n");
  writeFileSync(join(sqlDir, `amdm_registry_${String(f + 1).padStart(2, "0")}.sql`), parts.join("\n"), "utf8");
}

const count = (pred: (r: RegistryRow) => boolean) => rows.filter(pred).length;
console.log(
  [
    `rows: ${rows.length}, unique codes: ${codes.size}`,
    `codes with leading zero: ${count((r) => String(r.code).startsWith("0"))}`,
    `code lengths: ${JSON.stringify(Object.fromEntries([...new Set(rows.map((r) => String(r.code).length))].map((l) => [l, count((r) => String(r.code).length === l)])))}`,
    `barcodes: ${count((r) => r.barcode !== null)}, rx: ${count((r) => r.rx === true)}, otc: ${count((r) => r.rx === false)}`,
    `no ATC: ${count((r) => r.atc === null)}, no reg_date: ${count((r) => r.reg_date === null)}`,
    `-> ${join(outDir, "amdm_registry.csv")} and ${files} SQL files in ${sqlDir}`,
  ].join("\n"),
);
