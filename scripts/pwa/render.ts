// Pure part of the service worker build (unit-tested).

import ts from "typescript";
import { OFFLINE_PATH, type WorkerConfig } from "../../lib/offline/sw.ts";

/**
 * Everything the worker stores at install time: the offline shell, the manifest,
 * the icons and all static files of this build (scripts, styles, fonts), so the
 * lazily loaded scanner also works without a network.
 * Paths are relative to `.next/static` and to `public/icons`.
 */
export function precacheList(staticFiles: readonly string[], iconFiles: readonly string[]): string[] {
  const url = (prefix: string, file: string) => prefix + file.split("/").map(encodeURIComponent).join("/");
  const assets = staticFiles
    .filter((file) => !file.endsWith(".map") && !file.startsWith("service-worker/"))
    .map((file) => url("/_next/static/", file));
  const icons = iconFiles.map((file) => url("/icons/", file));
  return [OFFLINE_PATH, "/manifest.webmanifest", ...icons.sort(), ...assets.sort()];
}

/** TypeScript source of lib/offline/sw.ts → the classic script served as /sw.js. */
export function renderServiceWorker(source: string, config: WorkerConfig): string {
  const js = ts.transpileModule(source, {
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext, removeComments: true },
  }).outputText;
  const body = js.replace(/^export /gm, "");
  if (/^\s*(import|export)\b/m.test(body)) {
    throw new Error("lib/offline/sw.ts must stay a single file without imports");
  }
  return [
    "// Generated by scripts/pwa/build-sw.ts from lib/offline/sw.ts. Do not edit.",
    body.trim(),
    `installServiceWorker(self, ${JSON.stringify(config)});`,
    "",
  ].join("\n");
}
